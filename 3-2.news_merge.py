def source_score(row: pd.Series) -> int:
    d = domain_of(row.get("BestURL", ""))

    if any(
        x in d
        for x in [
            ".gov", ".go.kr", "europa.eu", "wto.org",
            "ustr.gov", "cbp.gov", "usitc.gov",
        ]
    ):
        return 10

    if clean(row.get("URLStatus", "")) in {"ORIGINAL", "RESOLVED"}:
        return 5

    return 0


def final_score(row: pd.Series) -> int:
    base = int(row.get("RuleScore", 0) or 0)
    return min(100, base + source_score(row))


def finalize(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        cols = [
            "Date", "CollectedAt", "Headline", "Summary", "BestURL",
            "Publisher", "Source", "InputKeyword", "InputFile",
            "CandidateGate", "IssueKey", "GateReason", "RuleScore",
            "FinalScore", "EventKey", "ClusterSize", "ClusterRank",
            "URLStatus", "EngineVersion",
        ]
        return pd.DataFrame(columns=cols)

    work = df.copy()
    work["FinalScore"] = work.apply(final_score, axis=1)
    work["EngineVersion"] = ENGINE_VERSION

    work = work.sort_values(
        ["FinalScore", "CandidateGate", "ReportDate"],
        ascending=[False, True, False],
        kind="stable",
    ).head(MAX_OUTPUT).copy()

    work["Priority"] = range(1, len(work) + 1)

    cols = [
        "Priority",
        "Date",
        "CollectedAt",
        "Headline",
        "Summary",
        "BestURL",
        "URLStatus",
        "Publisher",
        "Source",
        "InputKeyword",
        "InputFile",
        "CandidateGate",
        "IssueKey",
        "GateReason",
        "RuleScore",
        "FinalScore",
        "EventKey",
        "ClusterSize",
        "ClusterRank",
        "EngineVersion",
    ]

    for c in cols:
        if c not in work.columns:
            work[c] = ""

    return work[cols].reset_index(drop=True)


def update_cumulative(old: pd.DataFrame, final_df: pd.DataFrame) -> pd.DataFrame:
    if final_df.empty:
        return old.copy()

    combined = pd.concat([old, final_df], ignore_index=True, sort=False)

    combined["_url_key"] = combined["BestURL"].astype(str).map(normalize_url)
    combined["_title_key"] = combined["Headline"].astype(str).map(normalize_title)

    combined = combined.sort_values("Date", ascending=False, kind="stable")

    # Title is the safest cross-source key.
    combined = combined.drop_duplicates("_title_key", keep="first")

    combined = combined.drop(columns=["_url_key", "_title_key"], errors="ignore")
    return combined.reset_index(drop=True)


