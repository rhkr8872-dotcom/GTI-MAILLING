def title_key(row: pd.Series) -> str:
    title = normalize_title(row.get("Headline", ""))
    publisher = text_norm(row.get("Publisher", ""))
    return f"{publisher}|{title}" if title else ""


def global_title_key(row: pd.Series) -> str:
    return normalize_title(row.get("Headline", ""))


def dedup_current(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    if df.empty:
        return df, df.copy()

    work = df.copy()
    work["_url_key"] = work["BestURL"].map(normalize_url)
    work["_title_key"] = work.apply(title_key, axis=1)
    work["_global_title"] = work.apply(global_title_key, axis=1)

    work = work.sort_values(
        ["RuleScore", "ReportDate"],
        ascending=[False, False],
        kind="stable",
    )

    keep_idx = []
    dup_idx = []
    seen_urls = set()
    seen_titles = set()

    for idx, row in work.iterrows():
        u = clean(row["_url_key"])
        t = clean(row["_title_key"])

        is_dup = False

        if u and not looks_google_redirect(u) and u in seen_urls:
            is_dup = True

        if t and t in seen_titles:
            is_dup = True

        if is_dup:
            dup_idx.append(idx)
            continue

        keep_idx.append(idx)
        if u and not looks_google_redirect(u):
            seen_urls.add(u)
        if t:
            seen_titles.add(t)

    kept = work.loc[keep_idx].copy()
    dup = work.loc[dup_idx].copy()
    if not dup.empty:
        dup["RejectReason"] = "CURRENT_DUPLICATE"

    kept = kept.drop(columns=["_url_key", "_title_key", "_global_title"], errors="ignore")
    dup = dup.drop(columns=["_url_key", "_title_key", "_global_title"], errors="ignore")

    log(f"CURRENT DEDUP: {len(work)} -> {len(kept)} / removed={len(dup)}")
    return kept.reset_index(drop=True), dup.reset_index(drop=True)


