def standardize_input(df: pd.DataFrame, source_file: str) -> pd.DataFrame:
    out = pd.DataFrame(index=df.index)

    for target, aliases in COLUMN_ALIASES.items():
        col = first_existing(df, aliases)
        out[target] = df[col] if col else ""

    out["InputFile"] = source_file
    out["Date"] = pd.to_datetime(out["Date"], errors="coerce")
    out["CollectedAt"] = pd.to_datetime(out["CollectedAt"], errors="coerce")

    for c in [
        "Headline", "Summary", "URL", "OriginalURL",
        "Source", "Publisher", "InputKeyword", "InputFile",
    ]:
        out[c] = out[c].fillna("").astype(str)

    return out


def load_inputs() -> pd.DataFrame:
    frames = []

    for path in INPUT_FILES:
        if not path.exists():
            log(f"INPUT MISSING: {path.name}")
            continue

        try:
            raw = pd.read_excel(path, engine="openpyxl")
        except Exception as exc:
            log(f"INPUT READ FAIL: {path.name} / {type(exc).__name__}: {exc}")
            continue

        std = standardize_input(raw, path.name)
        frames.append(std)
        log(f"LOAD {path.name}: {len(std)}")

    if not frames:
        return pd.DataFrame(columns=list(COLUMN_ALIASES) + ["InputFile"])

    df = pd.concat(frames, ignore_index=True, sort=False)
    log(f"LOAD TOTAL: {len(df)}")
    return df


