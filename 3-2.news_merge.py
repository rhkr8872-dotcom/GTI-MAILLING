def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="GTI STEP3-2 REBUILD")
    p.add_argument("--hours", type=int, default=REPORT_HOURS)
    p.add_argument("--max-output", type=int, default=MAX_OUTPUT)
    return p.parse_args()


def main() -> int:
    global MAX_OUTPUT

    args = parse_args()
    MAX_OUTPUT = args.max_output

    log("=" * 80)
    log("GTI STEP3-2 REBUILD v1 START")
    log("=" * 80)

    df = load_inputs()

    if df.empty:
        log("NO INPUT DATA")
        safe_write(OUTPUT_FILE, finalize(df))
        return 0

    all_excluded = []

    # 1. Strict report window
    df, excluded = filter_recent(df, args.hours)
    all_excluded.append(excluded)

    # 2. URL selection / lightweight recovery
    df = prepare_urls(df)

    # 3. Evidence-based relevance
    df, excluded = apply_relevance(df)
    all_excluded.append(excluded)

    # 4. Same-run duplicates
    df, excluded = dedup_current(df)
    all_excluded.append(excluded)

    # 5. Same policy event clustering
    df, cluster_excluded = cluster_events(df)
    all_excluded.append(cluster_excluded)

    # 6. Clean cumulative only
    old = load_clean_cumulative()
    log(f"CLEAN CUMULATIVE LOAD: {len(old)}")

    df, excluded = historical_dedup(df, old)
    all_excluded.append(excluded)

    # 7. Final ranking
    final_df = finalize(df)

    # File-boundary 24h safety check
    if not final_df.empty:
        now = pd.Timestamp(datetime.now())
        cutoff = now - pd.Timedelta(hours=args.hours)
        dates = pd.to_datetime(final_df["Date"], errors="coerce")
        final_df = final_df[
            dates.notna()
            & (dates >= cutoff)
            & (dates <= now + pd.Timedelta(hours=2))
        ].copy().reset_index(drop=True)

        final_df["Priority"] = range(1, len(final_df) + 1)

    # 8. Cumulative
    cumulative_df = update_cumulative(old, final_df)

    # 9. Audit/excluded
    excluded_frames = [x for x in all_excluded if x is not None and not x.empty]
    excluded_df = (
        pd.concat(excluded_frames, ignore_index=True, sort=False)
        if excluded_frames
        else pd.DataFrame()
    )

    safe_write(OUTPUT_FILE, final_df)
    safe_write(CUMULATIVE_FILE, cumulative_df)
    safe_write(EXCLUDED_FILE, excluded_df)
    safe_write(CLUSTER_AUDIT_FILE, cluster_excluded)

    log("-" * 80)
    log(f"FINAL CANDIDATES: {len(final_df)}")
    if not final_df.empty:
        log(
            "FINAL GATE: "
            + str(final_df["CandidateGate"].value_counts().to_dict())
        )
        log(
            "FINAL ISSUE: "
            + str(final_df["IssueKey"].value_counts().head(10).to_dict())
        )
    log(f"CUMULATIVE: {len(cumulative_df)}")
    log(f"EXCLUDED/AUDIT: {len(excluded_df)}")
    log(f"SAVE: {OUTPUT_FILE}")
    log("=" * 80)
    log("GTI STEP3-2 REBUILD v1 DONE")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
