def choose_best_url(row: pd.Series) -> str:
    for col in ["OriginalURL", "URL"]:
        u = normalize_url(row.get(col, ""))
        if u:
            return u
    return ""


def looks_google_redirect(url: str) -> bool:
    d = domain_of(url)
    return d.endswith("google.com") or d.endswith("google.co.kr") or d.endswith("news.google.com")


def resolve_url(url: str) -> str:
    if not url or not looks_google_redirect(url):
        return url

    try:
        r = requests.get(
            url,
            timeout=URL_TIMEOUT,
            allow_redirects=True,
            headers={"User-Agent": "Mozilla/5.0"},
        )
        final = normalize_url(r.url)
        if final and not looks_google_redirect(final):
            return final
    except Exception:
        pass

    return url


def prepare_urls(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        return df

    work = df.copy()
    work["BestURL"] = work.apply(choose_best_url, axis=1)
    work["URLStatus"] = work["BestURL"].apply(
        lambda u: "GOOGLE_UNRESOLVED" if looks_google_redirect(u) else ("ORIGINAL" if u else "MISSING")
    )

    if RESOLVE_ORIGINAL_URL:
        unresolved_idx = work.index[work["URLStatus"].eq("GOOGLE_UNRESOLVED")].tolist()
        unresolved_idx = unresolved_idx[:URL_RESOLVE_LIMIT]

        for n, idx in enumerate(unresolved_idx, 1):
            old = work.at[idx, "BestURL"]
            new = resolve_url(old)
            work.at[idx, "BestURL"] = new
            work.at[idx, "URLStatus"] = (
                "RESOLVED" if new and not looks_google_redirect(new) else "GOOGLE_UNRESOLVED"
            )

            if n % 25 == 0:
                log(f"URL RESOLVE: {n}/{len(unresolved_idx)}")

    return work


