def log(msg: str) -> None:
    print(f"[{datetime.now():%Y-%m-%d %H:%M:%S}] {msg}")


def clean(v) -> str:
    if v is None:
        return ""
    try:
        if pd.isna(v):
            return ""
    except Exception:
        pass
    return re.sub(r"\s+", " ", str(v)).strip()


def text_norm(v) -> str:
    return clean(v).lower()


def normalize_title(v) -> str:
    s = text_norm(v)
    s = re.sub(r"\[[^\]]*\]", " ", s)
    s = re.sub(r"\([^\)]*\)", " ", s)
    s = re.sub(r"[^0-9a-z가-힣一-龥ぁ-ゔァ-ヴー\s]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def normalize_url(v) -> str:
    u = clean(v)
    if not u.startswith(("http://", "https://")):
        return ""
    try:
        p = urlparse(u)
        query = []
        for k, value in parse_qsl(p.query, keep_blank_values=True):
            if k.lower() not in {
                "utm_source", "utm_medium", "utm_campaign",
                "utm_term", "utm_content", "gclid", "fbclid",
            }:
                query.append((k, value))
        return urlunparse(
            (
                p.scheme.lower(),
                p.netloc.lower(),
                p.path.rstrip("/"),
                "",
                urlencode(query),
                "",
            )
        )
    except Exception:
        return u.lower()


def domain_of(url: str) -> str:
    try:
        return urlparse(clean(url)).netloc.lower()
    except Exception:
        return ""


def first_existing(df: pd.DataFrame, aliases: list[str]):
    index = {str(c).strip().lower(): c for c in df.columns}
    for alias in aliases:
        if alias.lower() in index:
            return index[alias.lower()]
    return None


def article_evidence(row: pd.Series) -> str:
    """Never include InputKeyword here."""
    return " ".join(
        [
            clean(row.get("Headline", "")),
            clean(row.get("Summary", "")),
            clean(row.get("Publisher", "")),
            clean(row.get("Source", "")),
        ]
    ).lower()


