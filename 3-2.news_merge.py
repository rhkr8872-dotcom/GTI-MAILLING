@dataclass
class GateResult:
    keep: bool
    gate: str
    issue: str
    reason: str
    score: int


def strong_signal(text: str) -> tuple[str, list[str]]:
    hits = []

    for issue, terms in STRONG_RULES.items():
        found = [t for t in terms if t in text]
        if found:
            hits.extend(found)
            return issue, found

    return "", hits


def contextual_signal(text: str) -> tuple[bool, str]:
    for lead, partners in CONTEXTUAL_RULES:
        if lead in text:
            for partner in partners:
                if partner in text:
                    return True, f"{lead}+{partner}"

    # Institution alone is not enough. It must coexist with trade-policy language.
    institution = next((x for x in POLICY_INSTITUTION_TERMS if x in text), "")
    if institution:
        policy_words = [
            "tariff", "customs", "trade restriction", "export control",
            "import restriction", "trade remedy", "market access",
            "관세", "통관", "수입규제", "수출통제", "무역장벽", "시장접근",
        ]
        policy = next((x for x in policy_words if x in text), "")
        if policy:
            return True, f"{institution}+{policy}"

    return False, ""


def generic_noise(text: str) -> str:
    for term in GENERIC_NOISE_TERMS:
        if term in text:
            return term

    for pattern in LOW_VALUE_PATTERNS:
        if re.search(pattern, text, flags=re.I):
            return pattern

    return ""


def samsung_signal(text: str) -> tuple[bool, list[str]]:
    hits = [x for x in SAMSUNG_TERMS if x in text]
    product_hits = [x for x in PRODUCT_TERMS if x in text]
    return bool(hits or product_hits), list(dict.fromkeys(hits + product_hits))


def evaluate_row(row: pd.Series) -> GateResult:
    text = article_evidence(row)

    issue, strong_hits = strong_signal(text)
    noise = generic_noise(text)

    # Explicit customs evidence overrides generic-noise words.
    if issue:
        samsung, samsung_hits = samsung_signal(text)
        score = 80
        if samsung:
            score += 10
        if len(strong_hits) >= 2:
            score += 5
        score = min(score, 100)
        return GateResult(
            True,
            "CORE",
            issue,
            "; ".join(strong_hits + samsung_hits[:4]),
            score,
        )

    # No explicit customs signal -> noise can reject immediately.
    if noise:
        return GateResult(False, "REJECT", "", f"GENERIC_NOISE:{noise}", 0)

    contextual, context_reason = contextual_signal(text)
    if contextual:
        samsung, samsung_hits = samsung_signal(text)
        score = 55
        if samsung:
            score += 10
        return GateResult(
            True,
            "CONTEXTUAL",
            "TRADE_POLICY",
            "; ".join([context_reason] + samsung_hits[:4]),
            min(score, 75),
        )

    return GateResult(False, "REJECT", "", "NO_CUSTOMS_TRADE_EVIDENCE", 0)


def apply_relevance(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    if df.empty:
        return df, df.copy()

    rows = []
    rejects = []

    for _, row in df.iterrows():
        r = row.copy()
        result = evaluate_row(r)

        r["CandidateGate"] = result.gate
        r["IssueKey"] = result.issue
        r["GateReason"] = result.reason
        r["RuleScore"] = result.score

        if result.keep:
            rows.append(r)
        else:
            r["RejectReason"] = result.reason
            rejects.append(r)

    kept = pd.DataFrame(rows)
    excluded = pd.DataFrame(rejects)

    if kept.empty:
        kept = df.iloc[0:0].copy()

    if excluded.empty:
        excluded = df.iloc[0:0].copy()

    core = int((kept.get("CandidateGate", pd.Series(dtype=str)) == "CORE").sum())
    contextual = int((kept.get("CandidateGate", pd.Series(dtype=str)) == "CONTEXTUAL").sum())

    log(
        f"RELEVANCE: {len(df)} -> {len(kept)} "
        f"/ CORE={core} / CONTEXTUAL={contextual} / rejected={len(excluded)}"
    )

    return kept.reset_index(drop=True), excluded.reset_index(drop=True)


