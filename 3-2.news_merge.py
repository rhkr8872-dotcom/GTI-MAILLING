def archive_legacy_cumulative() -> None:
    if not CUMULATIVE_FILE.exists():
        return

    try:
        old = pd.read_excel(CUMULATIVE_FILE, nrows=5, engine="openpyxl")
    except Exception:
        return

    valid_engine = (
        "EngineVersion" in old.columns
        and old["EngineVersion"].astype(str).eq(ENGINE_VERSION).any()
    )

    if valid_engine or not RESET_LEGACY_CUMULATIVE:
        return

    archive_dir = BASE_DIR / "archive"
    archive_dir.mkdir(parents=True, exist_ok=True)

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    dest = archive_dir / f"3-2.news_cumulative_LEGACY_{stamp}.xlsx"

    try:
        shutil.copy2(CUMULATIVE_FILE, dest)
        CUMULATIVE_FILE.unlink()
        log(f"LEGACY CUMULATIVE RESET: archived -> {dest}")
    except Exception as exc:
        log(f"LEGACY CUMULATIVE RESET WARN: {exc}")


def load_clean_cumulative() -> pd.DataFrame:
    archive_legacy_cumulative()

    if not CUMULATIVE_FILE.exists():
        return pd.DataFrame()

    try:
        old = pd.read_excel(CUMULATIVE_FILE, engine="openpyxl")
    except Exception as exc:
        log(f"CUMULATIVE READ WARN: {exc}")
        return pd.DataFrame()

    if "EngineVersion" not in old.columns:
        return pd.DataFrame()

    return old[old["EngineVersion"].astype(str).eq(ENGINE_VERSION)].copy()


def historical_dedup(df: pd.DataFrame, old: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    if df.empty or old.empty:
        return df, df.iloc[0:0].copy()

    old_urls = {
        normalize_url(x)
        for x in old.get("BestURL", pd.Series(dtype=str))
        if normalize_url(x) and not looks_google_redirect(normalize_url(x))
    }

    old_titles = {
        normalize_title(x)
        for x in old.get("Headline", pd.Series(dtype=str))
        if normalize_title(x)
    }

    keep = []
    dup = []

    for _, row in df.iterrows():
        u = normalize_url(row.get("BestURL", ""))
        t = normalize_title(row.get("Headline", ""))

        is_dup = (
            (u and not looks_google_redirect(u) and u in old_urls)
            or (t and t in old_titles)
        )

        if is_dup:
            r = row.copy()
            r["RejectReason"] = "HISTORICAL_DUPLICATE"
            dup.append(r)
        else:
            keep.append(row)

    kept = pd.DataFrame(keep)
    excluded = pd.DataFrame(dup)

    if kept.empty:
        kept = df.iloc[0:0].copy()
    if excluded.empty:
        excluded = df.iloc[0:0].copy()

    log(f"HISTORICAL DEDUP: {len(df)} -> {len(kept)} / removed={len(excluded)}")
    return kept.reset_index(drop=True), excluded.reset_index(drop=True)


