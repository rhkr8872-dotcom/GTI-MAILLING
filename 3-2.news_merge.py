def filter_recent(df: pd.DataFrame, hours: int) -> tuple[pd.DataFrame, pd.DataFrame]:
    if df.empty:
        return df, df.copy()

    now = pd.Timestamp(datetime.now())
    cutoff = now - pd.Timedelta(hours=hours)

    work = df.copy()
    work["ReportDate"] = pd.to_datetime(work["Date"], errors="coerce")

    keep = (
        work["ReportDate"].notna()
        & (work["ReportDate"] >= cutoff)
        & (work["ReportDate"] <= now + pd.Timedelta(hours=2))
    )

    excluded = work[~keep].copy()
    excluded["RejectReason"] = "OUTSIDE_REPORT_WINDOW_OR_NO_DATE"

    result = work[keep].copy().reset_index(drop=True)

    log(
        f"STRICT {hours}h FILTER: {len(df)} -> {len(result)} "
        f"/ removed={len(excluded)}"
    )

    if not result.empty:
        log(
            f"DATE RANGE: {result['ReportDate'].min()} "
            f"~ {result['ReportDate'].max()}"
        )

    return result, excluded


